import type { Node, Edge } from '@xyflow/react';

export interface SampleBoard {
  id: string;
  /** 人群标签（学者 / 架构师 / 自学者） */
  persona: string;
  title: string;
  /** 一句话说明（场景卡副标题） */
  desc: string;
  nodes: Node[];
  edges: Edge[];
}

type SampleCardData = {
  title?: string;
  question?: string;
  answer?: string;
  isNote?: boolean;
  noteContent?: string;
};

function chatNode(id: string, x: number, y: number, data: SampleCardData): Node {
  return { id, type: 'share', position: { x, y }, data, draggable: false };
}

function edge(source: string, target: string): Edge {
  return { id: `e-${source}-${target}`, source, target, type: 'smoothstep', animated: false };
}

